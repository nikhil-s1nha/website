#!/usr/bin/env node
/* Builds the Thoughts section from markdown in content/ into static HTML at the repo root.
   Run: node build/build.js
   No dependencies, no bundler - output is committed and served straight off Vercel.

   Migration behaviour: a post whose markdown body is still empty does NOT get a page.
   Its index entry keeps linking out to Medium, exactly as before. The moment you paste
   the text into the .md file, the native page appears and the link turns inward. */

const fs = require('fs');
const path = require('path');
const { render, renderPoem, esc } = require('./markdown.js');

const ROOT = path.join(__dirname, '..');
const BANNER = '<!-- generated by build/build.js - edit the markdown in content/, not this file -->';
const SITE = 'https://nikhilsinha.com';

const MONTHS = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];

const COLLECTIONS = {
  thoughts: { dir: 'content/thoughts', out: 'thoughts', tpl: 'post.html', back: '/thoughts',         backLabel: 'Thoughts' },
  poetry:   { dir: 'content/poetry',   out: 'poetry',   tpl: 'poem.html', back: '/thoughts#poetry',  backLabel: 'Poetry'   },
};

/* -- frontmatter -- */
function parse(src) {
  const m = src.replace(/^﻿/, '').match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!m) return { meta: {}, body: src };
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z_-]+)\s*:\s*(.*)$/);
    if (!kv) continue;
    let v = kv[2].trim().replace(/^["'](.*)["']$/, '$1');
    if (v === 'true') v = true;
    else if (v === 'false') v = false;
    meta[kv[1].trim()] = v;
  }
  return { meta, body: m[2] };
}

const fmtDate = iso => {
  const [y, mo, d] = String(iso).split('-').map(Number);
  return MONTHS[mo - 1] + ' ' + d + ', ' + y;
};

const plain = html => html.replace(/<[^>]+>/g, ' ').replace(/&[a-z]+;/gi, ' ').replace(/\s+/g, ' ').trim();

const excerpt = (html, n = 155) => {
  const t = plain(html);
  return esc(t.length <= n ? t : t.slice(0, t.lastIndexOf(' ', n)) + '…');
};

const fill = (tpl, vars) =>
  tpl.replace(/\{\{([A-Z_]+)\}\}/g, (m, k) => (k in vars ? String(vars[k]) : ''));

/* -- load -- */
function load(kind) {
  const cfg = COLLECTIONS[kind];
  const dir = path.join(ROOT, cfg.dir);
  if (!fs.existsSync(dir)) return [];

  return fs.readdirSync(dir)
    .filter(f => f.endsWith('.md'))
    .map(file => {
      const slug = file.replace(/\.md$/, '');
      const { meta, body } = parse(fs.readFileSync(path.join(dir, file), 'utf8'));
      if (!meta.title) throw new Error(cfg.dir + '/' + file + ': missing "title" in frontmatter');
      if (!meta.date)  throw new Error(cfg.dir + '/' + file + ': missing "date" in frontmatter');
      if (!/^\d{4}-\d{2}-\d{2}$/.test(meta.date))
        throw new Error(cfg.dir + '/' + file + ': date must be YYYY-MM-DD, got "' + meta.date + '"');
      // placeholder comments do not count as text - a stub keeps linking out to Medium
      const hasText = body.replace(/<!--[\s\S]*?-->/g, '').trim().length > 0;
      return { kind, cfg, slug, meta, body, written: hasText, url: '/' + cfg.out + '/' + slug };
    })
    .sort((a, b) => (a.meta.date < b.meta.date ? 1 : a.meta.date > b.meta.date ? -1 : 0));
}

/* -- pages -- */
function buildPages(posts, templates) {
  const written = [];

  posts.forEach((post, i) => {
    if (!post.written) return;                       // still lives on Medium only

    const { meta, cfg, kind } = post;
    const isVerse = kind === 'poetry';
    const bodyHtml = isVerse ? renderPoem(post.body) : render(post.body);

    // prev / next inside the same collection, skipping entries with no page yet
    const published = posts.filter(p => p.written);
    const at = published.indexOf(post);
    const newer = published[at - 1], older = published[at + 1];
    const nav = [
      newer ? '<a href="' + newer.url + '" rel="prev">&larr; ' + esc(newer.meta.title) + '</a>' : '',
      older ? '<a href="' + older.url + '" rel="next">' + esc(older.meta.title) + ' &rarr;</a>' : '',
    ].filter(Boolean).join('');

    let player = '';
    if (isVerse && meta.audio) {
      const file = path.join(ROOT, meta.audio.replace(/^\//, ''));
      if (!fs.existsSync(file)) {
        console.warn('  ! ' + post.slug + ': audio "' + meta.audio + '" not found, player omitted');
      } else {
        player =
          '<div class="player">\n' +
          '      <button class="player-btn" type="button" aria-label="Play reading">\n' +
          '        <svg class="icon-play" viewBox="0 0 10 12" aria-hidden="true"><path d="M0 0l10 6-10 6z"/></svg>\n' +
          '        <svg class="icon-pause" viewBox="0 0 10 12" aria-hidden="true"><path d="M0 0h3v12H0zM7 0h3v12H7z"/></svg>\n' +
          '      </button>\n' +
          '      <span class="player-label">Read aloud</span>\n' +
          '      <div class="player-track" role="slider" tabindex="0" aria-label="Seek"\n' +
          '           aria-valuemin="0" aria-valuemax="100" aria-valuenow="0"><div class="player-fill"></div></div>\n' +
          '      <span class="player-time">0:00 / 0:00</span>\n' +
          '      <audio preload="metadata" src="' + meta.audio + '"></audio>\n' +
          '    </div>';
      }
    }

    const html = fill(templates[cfg.tpl], {
      TITLE: esc(meta.title),
      BODY: bodyHtml,
      DATE: fmtDate(meta.date),
      ISO_DATE: meta.date,
      EXCERPT: excerpt(bodyHtml),
      CANONICAL: SITE + post.url,
      BACK_HREF: cfg.back,
      BACK_LABEL: cfg.backLabel,
      NAV: nav,
      PLAYER: player,
      MEDIUM: meta.medium
        ? '<a class="medium-link" href="' + meta.medium + '" target="_blank" rel="noopener">Medium</a>'
        : '',
    });

    const outPath = path.join(ROOT, cfg.out, post.slug + '.html');
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    fs.writeFileSync(outPath, BANNER + '\n' + html);
    written.push(outPath);
  });

  return written;
}

/* -- index -- */
function buildIndex(thoughts, poetry, templates) {
  const items = posts => posts.map((p, i) => {
    const internal = p.written;
    const href = internal ? p.url : (p.meta.medium || '#');
    const attrs = internal ? '' : ' target="_blank" rel="noopener"';
    const delay = Math.min(i * 0.05, 0.7).toFixed(2);
    const mark = (p.kind === 'poetry' && p.meta.audio) ? '<span class="post-audio-mark">&#9834;</span>' : '';
    return '        <a href="' + href + '"' + attrs + ' class="post-item" style="--d:' + delay + 's">\n' +
           '          <h2 class="post-title">' + esc(p.meta.title) + mark + '</h2>\n' +
           '          <p class="post-date">' + fmtDate(p.meta.date) + '</p>\n' +
           '        </a>';
  }).join('\n');

  const html = fill(templates['index.html'], {
    THOUGHTS_ITEMS: items(thoughts),
    POETRY_ITEMS: items(poetry),
  });

  const outPath = path.join(ROOT, 'thoughts', 'index.html');
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, BANNER + '\n' + html);
  return outPath;
}

/* -- sweep away pages whose markdown was deleted or emptied -- */
function prune(keep) {
  const kept = new Set(keep);
  for (const dir of ['thoughts', 'poetry']) {
    const d = path.join(ROOT, dir);
    if (!fs.existsSync(d)) continue;
    for (const f of fs.readdirSync(d)) {
      if (!f.endsWith('.html') || f === 'index.html') continue;
      const p = path.join(d, f);
      if (kept.has(p)) continue;
      // only ever remove files this script generated
      if (fs.readFileSync(p, 'utf8').startsWith(BANNER)) {
        fs.unlinkSync(p);
        console.log('  - pruned ' + path.relative(ROOT, p));
      }
    }
  }
}

/* -- main -- */
function main() {
  const templates = {};
  for (const f of fs.readdirSync(path.join(__dirname, 'templates'))) {
    templates[f] = fs.readFileSync(path.join(__dirname, 'templates', f), 'utf8');
  }

  const thoughts = load('thoughts');
  const poetry = load('poetry');

  const written = [...buildPages(thoughts, templates), ...buildPages(poetry, templates)];
  prune(written);
  buildIndex(thoughts, poetry, templates);

  const pending = [...thoughts, ...poetry].filter(p => !p.written);
  console.log('built ' + written.length + ' page(s) + thoughts/index.html');
  console.log('  thoughts: ' + thoughts.length + ' entries, poetry: ' + poetry.length + ' entries');
  if (pending.length) {
    console.log('  ' + pending.length + ' still awaiting text (index links out to Medium):');
    for (const p of pending) console.log('      ' + p.cfg.dir + '/' + p.slug + '.md');
  }
}

main();
